#!/usr/bin/env python3
"""Cross-check vectors for the C crypto primitives, produced with python-cryptography/hmac."""
import hmac, hashlib, os, random
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes
random.seed(7)
def h(b): return b.hex()
out = ["/* generated by gen_crypto_vectors.py */",
       "typedef struct { const char *key, *aad, *pt, *ct; unsigned long long ctr; } v_aead;"]
rows = []
for n, a in [(0,0),(1,0),(15,3),(16,16),(17,0),(63,12),(64,5),(65,64),(100,1),(129,33),(1000,16),(1400,0)]:
    key = bytes(random.randrange(256) for _ in range(32)); aad = bytes(random.randrange(256) for _ in range(a))
    pt = bytes(random.randrange(256) for _ in range(n)); ctr = random.choice([0, 1, 2**32+5, 2**63+9])
    nonce = b"\0"*4 + ctr.to_bytes(8, "little")
    ct = ChaCha20Poly1305(key).encrypt(nonce, pt, aad)
    rows.append('{"%s","%s","%s","%s",%dULL}' % (h(key), h(aad), h(pt), h(ct), ctr))
out.append("static const v_aead V_AEAD[] = {" + ",".join(rows) + "};")
out.append("typedef struct { const char *key, *msg, *mac; } v_hmac;")
rows = []
for kl, ml in [(0,0),(5,3),(32,100),(64,64),(65,10),(131,200)]:
    key = os.urandom(kl); msg = os.urandom(ml)
    rows.append('{"%s","%s","%s"}' % (h(key), h(msg), h(hmac.new(key, msg, hashlib.sha256).digest())))
out.append("static const v_hmac V_HMAC[] = {" + ",".join(rows) + "};")
out.append("typedef struct { const char *salt, *ikm, *okm; } v_hkdf;")
rows = []
for il in [0, 1, 32, 33]:
    salt = os.urandom(32); ikm = os.urandom(il)
    okm = HKDF(algorithm=hashes.SHA256(), length=64, salt=salt, info=b"").derive(ikm)
    rows.append('{"%s","%s","%s"}' % (h(salt), h(ikm), h(okm)))
out.append("static const v_hkdf V_HKDF[] = {" + ",".join(rows) + "};")
open("crypto_vectors.h", "w").write("\n".join(out) + "\n")
print("ok")
