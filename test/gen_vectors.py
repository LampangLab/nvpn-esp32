#!/usr/bin/env python3
"""Turns vectors.json (produced by refgen/, which uses the real nostr crate and
algorithms copied from nostr-vpn-core) into test/vectors.h for the C tests."""
import json, sys, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, "vectors.json")))

def c(s):
    if s is None: return "NULL"
    out = []
    for b in s.encode("utf-8"):
        if b in (0x22, 0x5c): out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7f and chr(b) != '?': out.append(chr(b))
        else: out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'

o = ["/* generated by gen_vectors.py — do not edit */"]
o.append("typedef struct { const char *in, *out; } v_str;")
o.append("static const v_str V_NETIDS[] = {" + ",".join("{%s,%s}" % (c(x["in"]), c(x["out"])) for x in d["netids"]) + "};")
o.append("static const v_str V_LABELS[] = {" + ",".join("{%s,%s}" % (c(x["in"]), c(x["out"])) for x in d["labels"]) + "};")
o.append("typedef struct { const char *sk, *pk, *npub; } v_key;")
o.append("static const v_key V_KEYS[] = {" + ",".join("{%s,%s,%s}" % (c(k["sk"]), c(k["pk"]), c(k["npub"])) for k in d["keys"]) + "};")
o.append("typedef struct { const char *net, *pk, *ip; } v_ip;")
o.append("static const v_ip V_IPS[] = {" + ",".join("{%s,%s,%s}" % (c(x["net"]), c(x["pk"]), c(x["ip"])) for x in d["ips"]) + "};")
o.append("typedef struct { const char *name, *event; int ok; const char *err, *network_id, *net_name, *id; unsigned long long signed_at; int n_dev; const char *dev[8]; int n_adm; const char *adm[4]; int n_al; const char *al[4][2]; } v_roster;")
rs = []
for r in d["rosters"]:
    dev = r.get("devices", []); adm = r.get("admins", []); al = r.get("aliases", {})
    rs.append("{%s,%s,%d,%s,%s,%s,%s,%dULL,%d,{%s},%d,{%s},%d,{%s}}" % (
        c(r["name"]), c(r["event"]), 1 if r["ok"] else 0, c(r.get("err")), c(r.get("network_id")), c(r.get("net_name")), c(r.get("id")),
        r.get("signed_at", 0), len(dev), ",".join(c(x) for x in dev) or "0", len(adm), ",".join(c(x) for x in adm) or "0",
        len(al) if "aliases" in r else -1, ",".join("{%s,%s}" % (c(k), c(v)) for k, v in al.items()) or "{0,0}"))
o.append("static const v_roster V_ROSTERS[] = {\n" + ",\n".join(rs) + "};")
s = d["schnorr"]
o.append("static const char *V_SCHNORR[3] = {%s,%s,%s};" % (c(s["pk"]), c(s["msg"]), c(s["sig"])))
open(os.path.join(here, "vectors.h"), "w").write("\n".join(o) + "\n")
print("vectors.h written")
